SELECT T_BB.BATTLE FROM
(SELECT O.BATTLE, COUNT(*) AS CNT_BB FROM CLASSES C
JOIN SHIPS S ON S.CLASS = C.CLASS
JOIN OUTCOMES O ON O.SHIP = S.NAME
WHERE C.TYPE = 'bb'
GROUP BY O.BATTLE) T_BB
INNER JOIN 
(SELECT O.BATTLE, COUNT(*) AS CNT_BC FROM CLASSES C
JOIN SHIPS S ON S.CLASS = C.CLASS
JOIN OUTCOMES O ON O.SHIP = S.NAME
WHERE C.TYPE = 'bc'
GROUP BY O.BATTLE) T_CC
ON T_BB.BATTLE = T_CC.BATTLE
WHERE T_BB.CNT_BB > T_CC.CNT_BC

SELECT O.BATTLE, COUNT(*) AS CNT_BB FROM CLASSES C
JOIN SHIPS S ON S.CLASS = C.CLASS
JOIN OUTCOMES O ON O.SHIP = S.NAME
WHERE C.TYPE = 'bb'
GROUP BY O.BATTLE
HAVING COUNT(*) > (
	SELECT COUNT(*) AS CNT_BC FROM CLASSES C1
	JOIN SHIPS S1 ON S1.CLASS = C1.CLASS
	JOIN OUTCOMES O1 ON O1.SHIP = S1.NAME
	WHERE C1.TYPE = 'bc' AND O1.BATTLE = O.BATTLE
	GROUP BY O1.BATTLE
)

