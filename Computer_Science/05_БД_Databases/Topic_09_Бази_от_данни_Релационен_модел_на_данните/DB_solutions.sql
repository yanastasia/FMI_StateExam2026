SELECT CLASS FROM CLASSES AS OC
WHERE OC.CLASS NOT IN
(SELECT C.CLASS FROM CLASSES AS C
LEFT JOIN SHIPS S ON C.CLASS = S.CLASS
LEFT JOIN OUTCOMES AS O ON O.SHIP = S.NAME
WHERE C.CLASS = OC.CLASS AND RESULT = 'damaged')

